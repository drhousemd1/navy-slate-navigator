beforeEach(() => { localStorage.clear(); mocks.user.id = 'account'; mocks.save.mockReset(); mocks.reset.mockResolvedValue(undefined); vi.stubGlobal('ResizeObserver', class { observe() {} unobserve() {} disconnect() {} }); });
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
describe.each([['task', Tasks, 'Title'], ['rule', Rules, 'Rule Title']] as const)('actual legacy %s page save contract', (kind, Page, label) => {
  it.each(['reject', 'unconfirmed'] as const)('keeps the real editor and draft on a %s mutation result, then closes only after confirmed retry', async result => {
    if (result === 'reject') mocks.save.mockRejectedValueOnce(new Error('Permission rejected'));
    else mocks.save.mockResolvedValueOnce(null);
    mocks.save.mockResolvedValue({ id: 'confirmed' });
    const view = render(<Page />);
    fireEvent.click(screen.getByRole('button', { name: 'Add definition' }));
    fireEvent.change(screen.getByRole('textbox', { name: label }), { target: { value: 'Keep this input' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));
    await waitFor(() => expect(mocks.save).toHaveBeenCalledOnce()); await waitFor(() => expect(screen.getByRole('button', { name: 'Save Changes' })).toBeTruthy());
    expect((screen.getByRole('textbox', { name: label }) as HTMLInputElement).value).toBe('Keep this input');
    if (kind === 'rule' && result === 'reject') expect(screen.getByRole('alert').textContent).toContain('Permission rejected');
    fireEvent(window, new Event('pagehide'));
    const key = editorDraftKey(scope, `${kind}-editor-new`);
    expect(JSON.parse(localStorage.getItem(key)!).values.title).toBe('Keep this input');
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));
    await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(2));
    await waitFor(() => expect(screen.queryByRole('textbox', { name: label })).toBeNull());
    expect(localStorage.getItem(key)).toBeNull(); view.unmount(); expect(localStorage.getItem(key)).toBeNull();
  });
  it('does not report success if the account becomes unavailable before submission', async () => {
    render(<Page />); fireEvent.click(screen.getByRole('button', { name: 'Add definition' }));
    fireEvent.change(screen.getByRole('textbox', { name: label }), { target: { value: 'Keep before sign-out' } });
    mocks.user.id = '';
    fireEvent.click(screen.getByRole('button', { name: 'Save Changes' }));
    await waitFor(() => expect(screen.getByRole('button', { name: 'Save Changes' })).toBeTruthy());
    expect(mocks.save).not.toHaveBeenCalled();
    expect((screen.getByRole('textbox', { name: label }) as HTMLInputElement).value).toBe('Keep before sign-out');
    fireEvent(window, new Event('pagehide'));
    expect(JSON.parse(localStorage.getItem(editorDraftKey(scope, `${kind}-editor-new`))!).values.title).toBe('Keep before sign-out');
  });

});
